import './_browser-stubs.mjs';
import test from 'node:test';
import assert from 'node:assert/strict';
import { BattleUI } from '../.test-build/ui/BattleUI.js';
import { networkRoomManager } from '../.test-build/engine/NetworkRoomManager.js';
import { GameState } from '../.test-build/game/GameState.js';

test('PvP prompts the remote attacker and defender, accepts only their current reply once', async t => {
  const previousDocument = globalThis.document;
  const previousChannel = globalThis.BroadcastChannel;
  globalThis.BroadcastChannel = undefined;
  const hidden = new Set();
  const menu = { classList: { add: name => hidden.add(name), remove: name => hidden.delete(name) }, innerText: '' };
  t.after(() => { networkRoomManager.leaveRoom(); globalThis.document = previousDocument; globalThis.BroadcastChannel = previousChannel; });
  networkRoomManager.createRoom();
  const game = new GameState();
  game.initGame([{ name: 'Host', classKey: 'warrior', isAI: false }, { name: 'Guest', classKey: 'mage', isAI: false }]);
  networkRoomManager.getRoomInfo().connectedPeers.push({ id: 'guest', name: 'Guest', playerIndex: 1, isHost: false });
  game.activeBattle = { attacker: { name: 'Guest', hp: 90, mp: 30, playerRef: game.players[1] }, defender: { name: 'Host', hp: 90, mp: 30, playerRef: game.players[0] }, isPlayerAttacking: true };
  globalThis.document = { getElementById: () => menu };
  const ui = Object.create(BattleUI.prototype);
  Object.assign(ui, { game, promptSequence: 0, playerSkillUsedThisBattle: false, isExecutingRound: false });
  const sent = [];
  const broadcast = networkRoomManager.broadcast;
  networkRoomManager.broadcast = p => sent.push(p);
  t.after(() => networkRoomManager.broadcast = broadcast);
  assert.equal(ui.promptRemotePlayer('attacker'), true);
  await Promise.resolve();
  assert.equal(hidden.has('hidden'), true);
  assert.equal(sent[0].payload.playerIndex, 1);
  assert.equal(sent[0].payload.actions.includes('skill'), true);
  let accepted = [];
  ui.handleAttackerInput = (action, remote) => accepted.push({ action, remote });
  const reply = { senderId: 'guest', payload: { promptId: sent[0].packetId, role: 'attacker', action: 'strike' } };
  ui.receiveRemoteBattlePacket({ ...reply, senderId: 'intruder' });
  ui.receiveRemoteBattlePacket({ ...reply, payload: { ...reply.payload, promptId: 'stale' } });
  assert.equal(accepted.length, 0);
  ui.receiveRemoteBattlePacket(reply); ui.receiveRemoteBattlePacket(reply);
  assert.deepEqual(accepted, [{ action: 'strike', remote: true }]);
  [game.activeBattle.attacker, game.activeBattle.defender] = [game.activeBattle.defender, game.activeBattle.attacker];
  ui.playerSkillUsedThisBattle = true;
  assert.equal(ui.promptRemotePlayer('defender'), true);
  ui.resendRemotePrompt(1);
  assert.notEqual(sent[1].packetId, sent[2].packetId);
  assert.deepEqual(sent[2].payload.actions, ['defend', 'counter', 'magic_guard', 'give_up']);
  await Promise.resolve();
});

test('human defender preserves the attacker choice after roles swap', t => {
  const previousDocument = globalThis.document;
  globalThis.document = undefined;
  t.after(() => globalThis.document = previousDocument);
  const ui = Object.create(BattleUI.prototype);
  ui.game = { activeBattle: { attacker: { playerRef: { isAI: false } }, defender: { playerRef: { isAI: false } }, isPlayerAttacking: false } };
  ui.isExecutingRound = false;
  ui.pendingAttackerAction = 'strike';
  let result;
  ui.executeRoundWithAnimation = (...actions) => result = actions;
  ui.handleDefenderInput('counter', true);
  assert.deepEqual(result, ['strike', 'counter']);
});
